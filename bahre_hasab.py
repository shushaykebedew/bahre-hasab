            መጠነ_ራብኢት = ዓመት_ዓለም // 4
            ወንጌል = {1: 'ማቲዎስ', 2: 'ማርቆስ', 3: 'ሉቋስ', 0: 'ዮሓንስ'}
            zemen = ዓመት_ዓለም % 4
            print(f"ዘመነ: {ወንጌል[zemen]} እዩ ።")


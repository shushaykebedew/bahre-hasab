                day = ((12 + ጥንተኦን + ደብረ_ዘይት + 2) % 7)
                print(f"ደብረ_ዘይት: {ወርሒ[7]}, {ደብረ_ዘይት}, {መዓልቲ[day]} ይውዕል")


            ጥንተኦን = ጥንተ_ቀመር - 1

            if ጥንተኦን == 0:
                day = 6
            elif ጥንተኦን == 1:
                day = 7

            መጥቅእ = (ወንበር * 19) % 30
            if ወንበር == 0 or ኣበቅቴ == 0 or መጥቅእ == 0:
                መጥቅእ = 30

            if መጥቅእ < 14:
                day = ((2 + ጥንተኦን + መጥቅእ + 2) % 7)
                print(f"መጥቅእ: {ወርሒ[2]}, {መጥቅእ}, {መዓልቲ[day]}")
            if መጥቅእ > 14:
                day = ((ጥንተኦን + መጥቅእ + 2) % 7)
                print(f"መጥቅእ: {ወርሒ[1]}, {መጥቅእ}, {መዓልቲ[day]}")

            xy = መዓልቲ[day]
            ተውሳከ_ዕለት = {'ቀዳም': 8, 'ሰንበት': 7, 'ሰኑይ': 6, 'ሰሉስ': 5, 'ረቡዕ': 4, 'ሓሙስ': 3, 'ዓርቢ': 2}
            መበጃ_ሓመር = (መጥቅእ + ተውሳከ_ዕለት[xy]) % 30
            a = መጥቅእ + ተውሳከ_ዕለት[xy]

            if መጥቅእ == 0 or መጥቅእ == 1:
                መጥቅእ = 30
            if መበጃ_ሓመር == 0:
                መበጃ_ሓመር = 30
            print(f"መበጃ_ሓመር: {መበጃ_ሓመር}")

            ነነዌ = መበጃ_ሓመር
            if መጥቅእ < 14 or መጥቅእ == 30 or a > 30:
                day = ((10 + ጥንተኦን + ነነዌ + 2) % 7)
                print(f"ነነዌ: {ወርሒ[6]}, {ነነዌ}, {መዓልቲ[day]}")
            else:
                day = ((8 + ጥንተኦን + ነነዌ + 2) % 7)
                print(f"ነነዌ: {ወርሒ[5]}, {ነነዌ}, {መዓልቲ[day]}")

            ዓብይ_ጾም = (14 + መበጃ_ሓመር) % 30
            if ዓብይ_ጾም == 0:
                ዓብይ_ጾም = 30

            if መጥቅእ < 14 and መበጃ_ሓመር >= 17:
                month = 7
                day = ((2 * (month - 1) + ጥንተኦን + ዓብይ_ጾም + 2) % 7)
                print(f"ዓብይ_ጾም: {ወርሒ[month]}, {ዓብይ_ጾም}, {መዓልቲ[day]} ይጅምር።")
            else:
                month = 6
                day = ((2 * (month - 1) + ጥንተኦን + ዓብይ_ጾም + 2) % 7)
                print(f"ዓብይ_ጾም: {ወርሒ[month]}, {ዓብይ_ጾም}, {መዓልቲ[day]} ይጅምር።")

            ደብረ_ዘይት = (መበጃ_ሓመር + 11) % 30
            if ደብረ_ዘይት == 0:
                ደብረ_ዘይት = 30

            if ወርሒ[month] == 'የካቲት' and ዓብይ_ጾም <= 3:
                day = ((10 + ጥንተኦን + ደብረ_ዘይት + 2) % 7)
                print(f"ደብረ_ዘይት: {ወርሒ[6]}, {ደብረ_ዘይት}, {መዓልቲ[day]} ይውዕል")
            elif ወርሒ[month] == 'መጋቢት' and (ዓብይ_ጾም == 4 or ዓብይ_ጾም == 5):
                day = ((14 + ጥንተኦን + ደብረ_ዘይት + 2) % 7)
                print(f"ደብረ_ዘይት: {ወርሒ[8]}, {ደብረ_ዘይት}, {መዓልቲ[day]} ይውዕል")
